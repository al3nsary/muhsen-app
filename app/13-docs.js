function screenDoc() {
  const parts = String(S.route.id || '').split('~');
  const t = taskById(parts[0]), k = DOCS[parts[1]] ? parts[1] : 'naql';
  if (!t) return screenTasks();
  const pages = docPages(t, k);
  return bar(DOCS[k].ar, { back: 1, right: '<button data-a="printdoc" aria-label="طباعة">' + icon('i-print') + '</button>' }) +
    '<div class="view">' + ground() +
    '<div class="docbar">' + icon('i-file','s18') +
      '<span class="sp"><b>' + DOCS[k].ar + '</b><br><span style="opacity:.7;font-weight:400">' +
      docNo(t, k) + ' · ' + E(t.title) + '</span></span>' +
      '<span class="pg">' + AR(pages.length) + ' صفحات</span></div>' +
    pages.map((p, i) => '<div class="page">' + p +
      '<div class="stamp" style="margin-top:14px">صفحة ' + AR(i + 1) + ' من ' + AR(pages.length) + '</div></div>').join('') +
    '<button class="btn l" data-a="printdoc">' + icon('i-print','s16') + 'حفظ نسخة PDF أو طباعة</button>' +
    '<button class="btn g" data-a="go" data-n="task" data-id="' + t.id + '">' +
      icon('i-tasks','s16') + 'العودة إلى المهمة</button>' +
    '</div>' + tabs();
}
