/* ============================ مستندات المهمة — عقد النقل وعقد السكن ============================ */
/* تظهر على مهام الاستقبال: استقبال المطار وتسجيل الدخول للفندق — ويقرأها كل من له صلاحية المهمة */

const DOC_KINDS = ['airport', 'checkin'];              /* مهام الاستقبال */
const hasDocs = t => DOC_KINDS.indexOf(t.kind) >= 0;
const DOCS = {
  naql:  { ar:'عقد النقل', sub:'نقل بري للحجاج', ref:'NQL', pages:2 },
  sakan: { ar:'عقد السكن', sub:'إيواء الحجاج', ref:'SKN', pages:2 }
};

const docNo = (t, k) => DOCS[k].ref + '-' + AR(String(t.code).slice(-4)) + '-' + AR(1447);
const dkv = (k, v) => '<div class="kv"><span>' + k + '</span><b>' + v + '</b></div>';

/* أزرار العقدين — تُعرض في بطاقة المهمة وداخل تفاصيلها */
function docButtons(t) {
  if (!hasDocs(t)) return '';
  return '<div class="docs">' + Object.keys(DOCS).map(k =>
    '<button class="docbtn" data-a="go" data-n="doc" data-id="' + t.id + '~' + k + '">' +
      '<span class="fi"><b>PDF</b></span>' +
      '<span class="sp"><b>' + DOCS[k].ar + '</b><span>' + docNo(t, k) + '</span></span>' +
      '<span class="eye" aria-label="معاينة">' + icon('i-eye','s16') + '</span></button>').join('') + '</div>';
}

